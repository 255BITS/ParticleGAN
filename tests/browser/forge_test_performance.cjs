// Run with Node and Playwright; reads the generated offline page, trains nothing.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const fs = require('node:fs');

(async () => {
  const options = { headless: true };
  if (process.env.CHROMIUM_EXECUTABLE) options.executablePath = process.env.CHROMIUM_EXECUTABLE;
  const browser = await chromium.launch(options);
  try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
  const errors = [];
  const directory = process.env.REPORT_SCREENSHOTS || '/tmp/forge-test-performance-browser';
  fs.mkdirSync(directory, { recursive: true });
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(pathToFileURL(path.resolve('reports/forge/test-performance.html')).href);
  await page.locator('#matrix tbody tr').first().waitFor();
  assert.equal(await page.locator('#scope').inputValue(), 'selected');
  assert.equal(await page.locator('#stats .stat').count(), 4);
  await page.selectOption('#filter', 'zero');
  assert(await page.locator('#matrix tbody tr').count() > 0);
  assert(await page.locator('#matrix tbody tr:not(.zero)').count() === 0);
  await page.locator('#matrix tbody td button').first().click();
  assert(await page.locator('#detail').isVisible());
  assert((await page.locator('#detailBody').innerText()).includes('original'));
  await page.keyboard.press('Escape');
  assert(!await page.locator('#detail').isVisible());

  await page.selectOption('#scope', 'forge');
  await page.fill('#search', 'vector_anisotropic');
  await page.fill('#recipe', 'G-angle');
  await page.selectOption('#filter', 'all');
  assert(await page.locator('#matrix tbody tr').count() > 0);
  assert((await page.locator('#matrix tbody').innerText()).includes('FAIL'));
  await page.fill('#search', 'vector_unequal_width');
  assert((await page.locator('#matrix tbody').innerText()).includes('PASS'));
  const width = page.locator('#matrix tbody tr').filter({ hasText: 'Scoped diagnostic' });
  assert.equal(await width.count(), 2); // Seeds stay in two exact protocol rows.
  assert((await width.nth(0).innerText()).includes('PASS'));
  assert((await width.nth(1).innerText()).includes('PASS'));
  // Current unmeasured definitions do not inherit these historical passes.
  assert(await page.locator('#matrix tbody tr').filter({ hasText: 'Unmeasured declaration' }).count() > 0);

  await page.fill('#recipe', 'Atlas location');
  await page.fill('#search', 'two_pole');
  assert((await page.locator('#matrix tbody').innerText()).includes('PASS'));
  assert((await page.locator('#matrix tbody').innerText()).includes('FAIL'));
  assert((await page.locator('#matrix tbody').innerText()).includes('ERROR'));
  await page.selectOption('#filter', 'error');
  assert((await page.locator('#matrix tbody').innerText()).includes('ERROR'));
  assert(!(await page.locator('#matrix tbody').innerText()).includes('PASS'));

  await page.selectOption('#filter', 'all');
  await page.fill('#recipe', 'Cell moment');
  await page.fill('#search', 'vector_anisotropic');
  const anisotropic = page.locator('#matrix tbody tr').filter({ hasText: 'Scoped diagnostic' });
  assert.equal(await anisotropic.count(), 1);
  assert.equal(await anisotropic.locator('td .badge.PASS').count(), 4);
  assert.equal(await anisotropic.locator('td .badge.FAIL').count(), 1);
  await anisotropic.locator('td button').first().click();
  await page.locator('#detailBody summary').filter({ hasText: 'Original gates, metrics' }).click();
  const detail = await page.locator('#detailBody').innerText();
  assert(detail.includes('effective_recipe') && detail.includes('candidate_revision'));
  assert(detail.includes('LOCAL_ONLY_NOT_PUBLISHED'));
  await page.keyboard.press('Escape');
  await page.fill('#recipe', 'Cell moment aggregate bures');
  await page.fill('#search', 'ring16_acquisition');
  const ring = page.locator('#matrix tbody tr').filter({ hasText: 'Scoped diagnostic' });
  assert.equal(await ring.count(), 1);
  assert.equal(await ring.locator('td .badge.FAIL').count(), 1);
  assert((await ring.innerText()).includes('1600 updates'));
  await page.fill('#recipe', 'Finite realization');
  await page.fill('#search', 'staggered100');
  await page.selectOption('#filter', 'incomplete');
  const prefix = page.locator('#matrix tbody tr').filter({ hasText: 'Scoped diagnostic' });
  assert.equal(await prefix.count(), 1);
  assert.equal(await prefix.locator('td .badge.INCOMPLETE').count(), 2);
  assert.equal(await prefix.locator('td .badge.PASS').count(), 0);
  assert((await prefix.innerText()).includes('7000 updates'));

  await page.selectOption('#filter', 'all');
  await page.fill('#recipe', 'cell-gradient-signal-');
  await page.fill('#search', 'gaussian1d_stability');
  const gaussian = page.locator('#matrix tbody tr').filter({ hasText: 'Scoped diagnostic' });
  assert.equal(await gaussian.count(), 1);
  assert((await gaussian.locator('td').first().innerText()).startsWith('5 / '));
  assert((await page.locator('#matrix thead').innerText()).includes('attenuated:'));
  await gaussian.locator('td button:has(.badge.PASS)').first().click();
  await page.locator('#detailBody summary').filter({ hasText: 'Original gates, metrics' }).click();
  const continued = await page.locator('#detailBody').innerText();
  assert(continued.includes('producer_dependency') && continued.includes('5000'));
  assert(continued.includes('cost_counted_in_original_producer_only'));
  await page.keyboard.press('Escape');
  await page.fill('#recipe', 'cell-gradient-signal-forward-kl-gp-v1');
  await page.fill('#search', 'mode_hold');
  const missingSamples = page.locator('#matrix tbody tr').filter({ hasText: 'Scoped diagnostic' });
  assert.equal(await missingSamples.count(), 1);
  await missingSamples.locator('td button:has(.badge.FAIL)').first().click();
  assert((await page.locator('#detailBody .warning').innerText()).includes('saved sample panels unavailable'));
  assert(await page.locator('#detailBody summary').filter({ hasText: 'Pinned source catalogs' }).count() > 0);
  await page.screenshot({ path: path.join(directory, 'reconciled-audit-gap.png') });
  await page.keyboard.press('Escape');
  await page.fill('#recipe', 'cell-memory-');
  await page.fill('#search', 'PRE_RUNTIME_HARDWARE_GUARD');
  await page.selectOption('#filter', 'error');
  const startup = page.locator('#matrix tbody tr').filter({ hasText: 'Scoped diagnostic' });
  assert.equal(await startup.count(), 1);
  assert((await startup.innerText()).includes('ERROR'));
  assert(!(await startup.innerText()).includes('PASS'));
  await page.selectOption('#filter', 'all');
  await page.fill('#recipe', 'cell-mixed-');
  await page.fill('#search', 'gaussian1d_stability');
  assert((await page.locator('#matrix thead').innerText()).includes('roles:'));
  assert((await page.locator('#matrix tbody').innerText()).includes('FAIL'));
  await page.screenshot({ path: path.join(directory, 'reconciled-roles.png'), fullPage: true });

  await page.selectOption('#filter', 'all');
  await page.fill('#recipe', 'f90962a5b351');
  await page.fill('#search', 'f90962a5b351');
  await page.screenshot({ path: path.join(directory, 'nonatlas.png'), fullPage: true });

  await page.selectOption('#scope', 'selected');
  await page.fill('#recipe', '');
  await page.fill('#search', 'this-test-does-not-exist');
  await page.selectOption('#filter', 'all');
  assert(await page.locator('#empty').isVisible());
  assert((await page.locator('#rows').innerText()).includes('0 of 0'));
  await page.fill('#search', '');
  await page.screenshot({ path: path.join(directory, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.table-wrap').scrollIntoViewIfNeeded();
  await page.locator('.table-wrap').evaluate(table => { table.scrollTop = 0; table.scrollLeft = 0; });
  await page.locator('#matrix tbody td button').first().click();
  assert(await page.locator('#detail').isVisible());
  await page.keyboard.press('Escape');
  await page.locator('.table-wrap').evaluate(table => { table.scrollTop = 0; table.scrollLeft = 0; });
  await page.screenshot({ path: path.join(directory, 'mobile.png'), fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: offline render, filters/counts, G-angle/Atlas, full reconciled recipes, continuation accounting, sample-gap warning, startup ERROR, role annotations, incomplete prefix, drill-down and mobile layout');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
